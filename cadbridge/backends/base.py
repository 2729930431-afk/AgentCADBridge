from typing import Any, Protocol


class CADBackend(Protocol):
    """A future RPC/native backend implements the same business boundary."""

    def connect(self, cad_type: str, launch: bool = False) -> dict: ...
    def documents(self, action: str, document_id: str = "", path: str = "", **kwargs) -> Any: ...
    def catalog(self, operation: str = "") -> Any: ...
    def execute(self, document_id: str, operation: str, arguments: dict) -> Any: ...
    def export_snapshot(self, document_id: str, path: str) -> dict: ...
